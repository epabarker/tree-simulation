"""Writes rust/core/src/math/pow_data.rs from glibc 2.39's e_pow_log_data.c and e_exp_data.c.

    python3 rust/tools/pow_tables.py <e_pow_log_data.c> <e_exp_data.c> > rust/core/src/math/pow_data.rs

The tables are copied, not regenerated: each hex-float literal (after glibc's exact scalings by
powers of two) becomes its IEEE bit pattern.
"""

import re
import struct
import sys


def bits(v: float) -> str:
    return f"0x{struct.unpack('<Q', struct.pack('<d', v))[0]:016x}"


def hexf(s: str) -> float:
    s = s.strip()
    m = re.fullmatch(r"(-?0x[0-9a-fA-F.]+p[-+]?\d+)(?:\s*\*\s*(-?\d+))?", s)
    if not m:
        raise ValueError(s)
    v = float.fromhex(m.group(1))
    return v * int(m.group(2)) if m.group(2) else v


log_src = open(sys.argv[1]).read()
exp_src = open(sys.argv[2]).read()
ln2hi = hexf(re.search(r"\.ln2hi = ([^,]+),", log_src).group(1))
ln2lo = hexf(re.search(r"\.ln2lo = ([^,]+),", log_src).group(1))
poly_block = re.search(r"\.poly = \{\n#if N == 128 && POW_LOG_POLY_ORDER == 8\n(.*?)#endif", log_src, re.S).group(1)
poly = [hexf(l.rstrip(",")) for l in poly_block.splitlines() if l and not l.startswith("//")]
rows = re.findall(r"^A\(([^,]+),\s*([^,]+),\s*([^)]+)\)", log_src, re.M)
assert len(poly) == 7 and len(rows) == 128, (len(poly), len(rows))

N = 128
invln2N = float.fromhex("0x1.71547652b82fep0") * N
negln2hiN = float.fromhex("-0x1.62e42fefa0000p-8")
negln2loN = float.fromhex("-0x1.cf79abc9e3b3ap-47")
shift = float.fromhex("0x1.8p52")
ep = re.search(r"#if N == 128 && EXP_POLY_ORDER == 5\n(.*?)#endif", exp_src, re.S).group(1)
epoly = [hexf(l.rstrip(",")) for l in ep.splitlines() if l and not l.startswith("//")]
tab_block = re.search(r"\.tab = \{\n#if N == 128\n(.*?)#endif", exp_src, re.S).group(1)
tab = re.findall(r"0x[0-9a-fA-F]+", tab_block)
assert len(epoly) == 4 and len(tab) == 2 * N, (len(epoly), len(tab))

out = []
out.append("//! glibc 2.39's pow tables (sysdeps/ieee754/dbl-64/e_pow_log_data.c, e_exp_data.c), from")
out.append("//! Arm's optimized-routines: Copyright (c) 2018-2024 Arm Limited, SPDX MIT OR")
out.append("//! Apache-2.0 WITH LLVM-exception; LGPL-2.1+ as distributed in glibc. Generated by")
out.append("//! rust/tools/pow_tables.py; do not edit.")
out.append("")
out.append("#![allow(clippy::unreadable_literal)]")
out.append("")
out.append(f"pub const LN2HI: f64 = f64::from_bits({bits(ln2hi)});")
out.append(f"pub const LN2LO: f64 = f64::from_bits({bits(ln2lo)});")
out.append("/// A[0..7]; A[0] = −½, the rest scaled as glibc scales them.")
out.append("pub const POLY: [f64; 7] = [")
out += [f"    f64::from_bits({bits(v)})," for v in poly]
out.append("];")
out.append("/// (invc, logc, logctail) for each of the 128 subintervals.")
out.append("pub const TAB: [[f64; 3]; 128] = [")
for a, b, c in rows:
    out.append(f"    [f64::from_bits({bits(hexf(a))}), f64::from_bits({bits(hexf(b))}), f64::from_bits({bits(hexf(c))})],")
out.append("];")
out.append(f"pub const INV_LN2_N: f64 = f64::from_bits({bits(invln2N)});")
out.append(f"pub const NEG_LN2_HI_N: f64 = f64::from_bits({bits(negln2hiN)});")
out.append(f"pub const NEG_LN2_LO_N: f64 = f64::from_bits({bits(negln2loN)});")
out.append(f"pub const SHIFT: f64 = f64::from_bits({bits(shift)});")
out.append("/// C2 … C5.")
out.append("pub const EXP_POLY: [f64; 4] = [")
out += [f"    f64::from_bits({bits(v)})," for v in epoly]
out.append("];")
out.append("/// 2^(k/N) ≈ H[k]·(1 + T[k]): T[2k] = bits of T[k], T[2k+1] = bits of H[k] − (k << 52)/N.")
out.append("pub const EXP_TAB: [u64; 256] = [")
for i in range(0, len(tab), 2):
    out.append(f"    {tab[i]}, {tab[i + 1]},")
out.append("];")
print("\n".join(out))
